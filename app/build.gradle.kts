// Fail early with a helpful message if the native library hasn't been built yet.
tasks.register("checkNativeLib") {
    doLast {
        val libPath = file("src/main/jniLibs/arm64-v8a/libelftrace.so")
        if (!libPath.exists()) {
            throw GradleException(
                "\n\n" +
                "================================================================\n" +
                "  libelftrace.so is missing.\n" +
                "  Build it first from elftrace-core/:\n" +
                "\n" +
                "    cd elftrace-core\n" +
                "    cargo ndk -t arm64-v8a -p 24 -o ../app/src/main/jniLibs build --release\n" +
                "    cd ..\n" +
                "    ./gradlew assembleRelease\n" +
                "\n" +
                "  (The .so is generated by cargo, not committed to the repo.)\n" +
                "================================================================\n\n"
            )
        }
    }
}

tasks.named("preBuild") {
    dependsOn("checkNativeLib")
}
